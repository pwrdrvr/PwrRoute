#!/usr/bin/env bash
# Write licenses/velopack.txt: the license notices for the Rust crates
# compiled into Velopack's native binaries, which `vpk pack` adds to our
# release packages (Update.exe, Setup.exe, the launcher stub and the MSI's
# velopack_wix DLL on Windows x64; UpdateMac on macOS).
#
# Those binaries are built from velopack/velopack's own Cargo.lock, not ours,
# so cargo-about cannot see them from this workspace. This clones Velopack at
# the vpk version pinned in install-vpk.sh, trims its workspace to the crates
# behind those binaries (src/bins, src/wix-dll and their path dependencies),
# and runs cargo-about there with our about.toml and licenses/velopack.hbs.
# Trimming only drops lockfile entries; the script fails if any version moves.
#
# Rerun it whenever VPK_VERSION changes, then `cargo xtask licenses`. Check
# the license ids it prints against deny.toml: a new id is a legal decision.
#
# Needs git, cargo, cargo-about and perl.
#
# usage: scripts/release/velopack-notices.sh
set -euo pipefail

repo=$(cd "$(dirname "$0")/../.." && pwd)
version=$(sed -n 's/^VPK_VERSION=//p' "$repo/scripts/release/install-vpk.sh")
[ -n "$version" ] || { echo "no VPK_VERSION in install-vpk.sh" >&2; exit 1; }

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
git -c advice.detachedHead=false clone -q --depth 1 --branch "$version" \
  https://github.com/velopack/velopack.git "$work/velopack"
cd "$work/velopack"

perl -0pi -e 's/members = \[.*?\]/members = ["src\/bins", "src\/l18n", "src\/lib-rust", "src\/wix-dll"]/s; s/exclude = \[.*?\]\n//s' Cargo.toml
# The workspace crates have no license file of their own; give each the
# repository's, so cargo-about quotes it rather than a blank MIT template.
for dir in src/bins src/l18n src/lib-rust src/wix-dll; do
  cp LICENSE "$dir/LICENSE"
done

packages() { awk '/^name = /{n=$3} /^version = /{print n, $3}' Cargo.lock | sort -u; }
packages > "$work/upstream.txt"
cargo metadata --format-version 1 >/dev/null
packages > "$work/trimmed.txt"
if [ -n "$(comm -13 "$work/upstream.txt" "$work/trimmed.txt")" ]; then
  echo "trimming the workspace changed Cargo.lock versions:" >&2
  comm -13 "$work/upstream.txt" "$work/trimmed.txt" >&2
  exit 1
fi

cargo about generate -c "$repo/about.toml" "$repo/licenses/velopack.hbs" \
  --target x86_64-pc-windows-msvc --target aarch64-apple-darwin --target x86_64-apple-darwin \
  --workspace --locked --fail -o "$work/crates.txt"

{
  cat <<HEADER
Velopack's Native Binaries
--------------------------

The Rust crates compiled into Velopack $version's Update.exe, Setup.exe,
launcher stub and velopack_wix DLL (Windows x64) and UpdateMac (macOS), which
\`vpk pack\` adds to PwrRoute's release packages. Velopack's own crates
(velopack, velopack_bins, velopack_l18n, velopack_wix) are listed too.
Generated by scripts/release/velopack-notices.sh from Velopack's Cargo.lock at
tag $version; do not edit by hand.

HEADER
  cat "$work/crates.txt"
} > "$repo/licenses/velopack.txt"

echo "wrote licenses/velopack.txt; license ids in use:"
sed -n '/^License Texts/,$p' "$repo/licenses/velopack.txt" \
  | awk '/^-{20,}$/ && prev ~ /\)$/ { sub(/.*\(/, "", prev); sub(/\)$/, "", prev); print "  " prev } { prev = $0 }' \
  | sort -u

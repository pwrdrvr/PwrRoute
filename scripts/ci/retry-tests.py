#!/usr/bin/env python3
"""Run a Cargo selection once, then retry only individually identified failures.

The inventory and JUnit report are generated by the pinned nextest in this job.
Doctests stay with Cargo: a doctest failure makes the slice non-retriable.
"""
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
TARGET = (ROOT / os.environ.get('CARGO_TARGET_DIR', 'target')).resolve()
OUT = TARGET / 'ci-retry'
JUNIT = TARGET / 'nextest' / 'ci' / 'junit.xml'
BUDGET = 20


def command(args, *, capture=False, env=None):
    print('+', ' '.join(args), flush=True)
    return subprocess.run(args, cwd=ROOT, env=env, text=True,
                          stdout=subprocess.PIPE if capture else None)


def selection(kind):
    return ['--workspace'] if kind == 'unit' else ['-p', 'pwrroute-e2e']


def environment(kind, retry=False):
    env = os.environ.copy()
    if kind == 'e2e':
        app = TARGET / ('e2e/PwrRoute.app' if sys.platform == 'darwin' else
                        'debug/pwrroute.exe' if os.name == 'nt' else 'debug/pwrroute')
        env['PWRROUTE_E2E_APP'] = str(app)
        env['PWRROUTE_E2E_ARTIFACTS'] = str(TARGET / ('e2e-retry-artifacts' if retry else 'e2e-artifacts'))
        env['PWRROUTE_E2E_SCREENSHOTS'] = '1'
    return env


def inventory(data, filtered=False):
    tests = set()
    binaries = set()
    suites = data['rust-suites']
    if not suites:
        raise ValueError('no test executables discovered')
    total = 0
    for binary_id, suite in suites.items():
        if suite['status'] != 'listed' or suite['binary-id'] != binary_id:
            raise ValueError('unlisted or ambiguous test executable')
        path = os.path.normcase(os.path.realpath(suite['binary-path']))
        if path in binaries:
            raise ValueError('duplicate executable')
        binaries.add(path)
        for name, case in suite['testcases'].items():
            total += 1
            if case['kind'] != 'test':
                raise ValueError('unsupported non-test case')
            match = case['filter-match']
            if match['status'] == 'matches':
                if case['ignored']:
                    raise ValueError('unexpected selected ignored test')
                tests.add((binary_id, name))
            elif match != {'status': 'mismatch', 'reason': 'ignored'} and not (
                filtered and match == {'status': 'mismatch', 'reason': 'expression'}
            ):
                raise ValueError('unexpected filtered test')
    if total != data['test-count'] or not tests:
        raise ValueError('empty or inconsistent test inventory')
    return tests, binaries


def report(path, expected):
    root = ET.parse(path).getroot()
    if root.tag != 'testsuites' or int(root.attrib['errors']) != 0 or int(root.attrib['skipped']) != 0:
        raise ValueError('invalid JUnit root')
    seen = {}
    for suite in root.findall('testsuite'):
        binary = suite.attrib['name']
        cases = suite.findall('testcase')
        if len(cases) != int(suite.attrib['tests']) or int(suite.attrib['errors']) != 0 or int(suite.attrib['skipped']) != 0:
            raise ValueError('incomplete JUnit suite')
        suite_failures = 0
        for case in cases:
            identity = (binary, case.attrib['name'])
            if identity in seen or case.attrib['classname'] != binary:
                raise ValueError('ambiguous JUnit identity')
            failure_nodes = case.findall('failure')
            if len(failure_nodes) > 1:
                raise ValueError('ambiguous test result')
            failure = failure_nodes[0] if failure_nodes else None
            if case.find('error') is not None or case.find('skipped') is not None:
                raise ValueError('test error or unexpected skip')
            output = case.findtext('system-out') or ''
            if failure is None:
                marker = r'^test result: ok\. 1 passed; 0 failed; 0 ignored;'
                line = f'test {identity[1]} ... ok'
                outcome = 'passed'
            else:
                suite_failures += 1
                if failure.attrib.get('type') != 'test failure with exit code 101':
                    raise ValueError('test process failed outside libtest')
                marker = r'^test result: FAILED\. 0 passed; 1 failed; 0 ignored;'
                line = f'test {identity[1]} ... FAILED'
                outcome = 'failed'
            if not re.search(marker, output, re.MULTILINE) or \
                    'running 1 test' not in output.splitlines() or line not in output.splitlines():
                raise ValueError('missing single-test completion evidence')
            seen[identity] = outcome
        if suite_failures != int(suite.attrib['failures']):
            raise ValueError('JUnit suite failure count mismatch')
    if len(seen) != int(root.attrib['tests']) or set(seen) != expected:
        raise ValueError('JUnit identities do not match selected inventory')
    if sum(x == 'failed' for x in seen.values()) != int(root.attrib['failures']):
        raise ValueError('JUnit failure count mismatch')
    return seen


def save(data):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'report.json').write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8')


def load():
    return json.loads((OUT / 'report.json').read_text(encoding='utf-8'))


def expression(failures):
    def escape(value):
        return ''.join({'\\': r'\\', ')': r'\)', ',': r'\,', '\n': r'\n', '\r': r'\r', '\t': r'\t'}.get(c, c) for c in value)
    return ' | '.join('(binary_id(=' + escape(binary) + ') & test(=' + escape(name) + '))'
                      for binary, name in failures)


def list_tests(kind, extra=()):
    result = command(['cargo', 'nextest', 'list', *selection(kind), '--locked',
                      '--message-format', 'json', *extra], capture=True,
                     env=environment(kind, retry=bool(extra)))
    if result.returncode:
        raise ValueError('test discovery failed')
    return inventory(json.loads(result.stdout), filtered=bool(extra))


def first(kind, platform):
    state = {'version': 1, 'type': kind, 'platform': platform, 'slice': 'all',
             'run_id': os.environ.get('GITHUB_RUN_ID', 'local'),
             'attempt': os.environ.get('GITHUB_RUN_ATTEMPT', 'local'),
             'initial': 'incomplete', 'retry': 'not-run', 'failures': []}
    OUT.mkdir(parents=True, exist_ok=True)
    for name in ('initial.xml', 'retry.xml'):
        (OUT / name).unlink(missing_ok=True)
    save(state)
    env = environment(kind)
    # Cargo's target list is the oracle for nextest's executable selection.
    build = command(['cargo', 'test', *selection(kind), '--locked', '--no-run',
                     '--message-format=json'], capture=True, env=env)
    if build.returncode:
        raise ValueError('Cargo test build failed')
    artifacts = [json.loads(line) for line in build.stdout.splitlines()]
    binaries = {os.path.normcase(os.path.realpath(a['executable'])) for a in artifacts
                if a.get('profile', {}).get('test') and a.get('executable')}
    expected, listed_binaries = list_tests(kind)
    if binaries != listed_binaries:
        raise ValueError('Cargo and nextest selected different test executables')
    OUT.mkdir(parents=True, exist_ok=True)
    JUNIT.unlink(missing_ok=True)
    opts = ['--test-threads=1'] if kind == 'e2e' else []
    result = command(['cargo', 'nextest', 'run', *selection(kind), '--locked',
                      '--profile', 'ci', '--no-fail-fast', '--retries', '0', *opts], env=env)
    # Doctests are part of cargo test but are not supported by nextest.
    docs = command(['cargo', 'test', *selection(kind), '--locked', '--doc', '--no-fail-fast'], env=env)
    outcomes = report(JUNIT, expected)
    shutil.copyfile(JUNIT, OUT / 'initial.xml')
    failures = sorted(k for k, v in outcomes.items() if v == 'failed')
    state['failures'] = [{'binary': b, 'name': n, 'retry': 'not-run'} for b, n in failures]
    state['initial'] = 'complete'
    state['selected'] = len(expected)
    state['doctests'] = 'passed' if docs.returncode == 0 else 'failed'
    if result.returncode != (100 if failures else 0) or docs.returncode:
        state['initial'] = 'incomplete'
        save(state)
        raise ValueError('runner or doctest failure cannot be retried')
    save(state)
    print(f'Initially failed tests: {len(failures)} of {BUDGET} allowed', flush=True)


def retry(kind):
    state = load()
    if state['type'] != kind or state['initial'] != 'complete':
        raise ValueError('missing or incomplete initial report')
    if state.get('run_id', 'local') != os.environ.get('GITHUB_RUN_ID', 'local') or \
            state.get('attempt', 'local') != os.environ.get('GITHUB_RUN_ATTEMPT', 'local'):
        raise ValueError('report belongs to another run or attempt')
    failures = [(x['binary'], x['name']) for x in state['failures']]
    print(f'Retry budget: {len(failures)} of {BUDGET} initially failed tests', flush=True)
    if len(failures) > BUDGET or len(set(failures)) != len(failures):
        state['retry'] = 'budget-exceeded' if len(failures) > BUDGET else 'invalid'
        save(state)
        raise ValueError('retry budget exceeded or ambiguous identity')
    if not failures:
        state['retry'] = 'not-needed'
        save(state)
        return
    state['retry'] = 'incomplete'
    save(state)
    filt = ['-E', expression(failures)]
    # The filter must select exactly the failures, including in other binaries.
    selected, _ = list_tests(kind, filt)
    if selected != set(failures):
        raise ValueError('retry filter does not select the exact failure set')
    JUNIT.unlink(missing_ok=True)
    opts = ['--test-threads=1'] if kind == 'e2e' else []
    result = command(['cargo', 'nextest', 'run', *selection(kind), '--locked',
                      '--profile', 'ci', '--no-fail-fast', '--retries', '0', *opts, *filt],
                     env=environment(kind, retry=True))
    outcomes = report(JUNIT, selected)
    shutil.copyfile(JUNIT, OUT / 'retry.xml')
    for item in state['failures']:
        item['retry'] = outcomes[(item['binary'], item['name'])]
    state['retry'] = 'passed' if result.returncode == 0 and all(v == 'passed' for v in outcomes.values()) else 'failed'
    save(state)
    if state['retry'] != 'passed':
        raise ValueError('one or more selected retries failed')


def main():
    phase, kind = sys.argv[1:3]
    if kind not in ('unit', 'e2e'):
        raise ValueError('unknown test kind')
    if phase == 'first':
        first(kind, sys.argv[3])
    elif phase == 'retry':
        retry(kind)
    else:
        raise ValueError('unknown phase')


if __name__ == '__main__':
    try:
        main()
    except (KeyError, ValueError, OSError, ET.ParseError, json.JSONDecodeError) as error:
        print(f'CI retry failed closed: {error}', file=sys.stderr)
        sys.exit(1)

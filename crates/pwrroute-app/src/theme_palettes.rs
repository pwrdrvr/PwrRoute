//! floor moved by the least OKLCH lightness that clears it. Catppuccin
//! (Copyright (c) 2021 Catppuccin) and Solarized (Copyright (c) 2011 Ethan
//! Schoonover) are MIT; their notices are in `THIRD_PARTY_LICENSES`.

